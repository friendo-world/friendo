// Mirrors the built admin SPA (runtime/go/admin/spa) into an ES module the edge
// Worker can embed and serve, so both runtimes ship the byte-identical bundle.
//
// Run from the admin/ directory (see `npm run admin`). Assets are stored as
// UTF-8 text — the current bundle is only HTML/JS/CSS. If the admin ever ships
// binary assets (fonts, images), switch those entries to base64.

import { readFileSync, readdirSync, writeFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const spaDir = join(import.meta.dirname, "..", "..", "runtime", "go", "admin", "spa");
const outFile = join(import.meta.dirname, "..", "..", "runtime", "edge", "spa-bundle.js");

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon",
};

function contentType(path) {
  const ext = path.slice(path.lastIndexOf("."));
  return TYPES[ext] || "application/octet-stream";
}

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

const assets = {};
let index = "";
for (const file of walk(spaDir)) {
  const rel = relative(spaDir, file).split("\\").join("/");
  const body = readFileSync(file, "utf8");
  if (rel === "index.html") {
    index = body;
  } else {
    assets["/" + rel] = { type: contentType(rel), body };
  }
}

const banner = "// AUTO-GENERATED by admin/scripts/bundle-edge.mjs — do not edit by hand.\n";
const module =
  banner +
  "export const SPA_INDEX = " +
  JSON.stringify(index) +
  ";\n" +
  "export const SPA_ASSETS = " +
  JSON.stringify(assets) +
  ";\n";

writeFileSync(outFile, module);
console.log(`Wrote ${outFile} (${Object.keys(assets).length} assets)`);
