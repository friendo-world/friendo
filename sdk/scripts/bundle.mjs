// Mirrors the hand-written SDK (sdk/friendo.js) into both runtimes so each ships
// the byte-identical client:
//   - runtime/go/sdk/friendo.js   — embedded via go:embed, served at /friendo.js
//   - runtime/edge/sdk-bundle.js  — an ES module exporting FRIENDO_JS as a string,
//                                   imported by the Worker and served at /friendo.js
//
// Run with `npm run sdk`. The SDK is dependency-free vanilla JS, so there is no
// bundler step — this is a straight copy + string-wrap.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";

const root = join(import.meta.dirname, "..", "..");
const src = join(root, "sdk", "friendo.js");
const goOut = join(root, "runtime", "go", "sdk", "friendo.js");
const edgeOut = join(root, "runtime", "edge", "sdk-bundle.js");

const source = readFileSync(src, "utf8");

mkdirSync(dirname(goOut), { recursive: true });
writeFileSync(goOut, source);

const banner = "// AUTO-GENERATED by sdk/scripts/bundle.mjs — edit sdk/friendo.js instead.\n";
writeFileSync(edgeOut, banner + "export const FRIENDO_JS = " + JSON.stringify(source) + ";\n");

console.log(`Wrote ${goOut} and ${edgeOut} (${source.length} bytes)`);
